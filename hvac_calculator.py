from fpdf import FPDF
from datetime import datetime

def generate_pdf_report(data: dict, result: dict, mode: str) -> str:
    """Generate PDF with Unicode support (emojis work)"""
    class PDF(FPDF):
        def header(self):
            self.set_font("Arial", "B", 16)
            self.cell(0, 10, "HVAC LOAD CALCULATION REPORT", ln=True, align="C")
            self.ln(5)

    pdf = PDF()
    pdf.add_page()
    
    # Use Arial (better emoji support than Helvetica)
    pdf.set_font("Arial", "", 12)
    
    pdf.cell(0, 8, f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M')}", ln=True)
    pdf.cell(0, 8, f"Type: {mode}", ln=True)
    pdf.ln(10)

    # Input Data
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "INPUT PARAMETERS", ln=True)
    pdf.set_font("Arial", "", 11)
    for key, value in data.items():
        if key != "mode":
            nice_key = key.replace('_', ' ').title()
            pdf.cell(0, 6, f"• {nice_key}: {value}", ln=True)
    
    pdf.ln(10)

    # Results
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "RESULTS", ln=True)
    pdf.set_font("Arial", "", 11)

    if "Heating" in mode:
        pdf.cell(0, 8, f"Total Heating Load : {result.get('total_btu_hr', 'N/A')} BTU/hr", ln=True)
        pdf.cell(0, 8, f"Recommended Airflow : {result.get('cfm', 'N/A')} CFM", ln=True)
    else:
        pdf.cell(0, 8, f"Total Cooling Load : {result.get('total_btu_hr', 'N/A')} BTU/hr", ln=True)
        pdf.cell(0, 8, f"Capacity           : {result.get('tons', 'N/A')} Tons", ln=True)
        pdf.cell(0, 8, f"Supply Airflow     : {result.get('cfm', 'N/A')} CFM", ln=True)

    pdf.ln(20)
    pdf.set_font("Arial", "I", 10)
    pdf.cell(0, 8, "Generated by HVAC Telegram Bot", ln=True, align="C")

    filename = f"hvac_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    pdf.output(filename)
    return filename